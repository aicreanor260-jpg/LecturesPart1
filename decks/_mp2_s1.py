from _mp2_kit import slide, step, panel, row, pk, node, arrow, ico


def chain(names, subs, labels, zone="MPLS-сеть", foot="LSP — путь коммутации по меткам", rt="i03a_rt.png", ip="i03a_ip.png"):
    """IP → LER/LSR… → IP: каждый переход — отдельный шаг (пакет с новой меткой появляется после узла)."""
    parts = [step(node(ico(ip, 54), "IP-пакет", "(без метки)") + arrow())]
    inner = []
    for i, (n, s) in enumerate(zip(names, subs)):
        lab = labels[i] if i < len(labels) else None
        tail = (arrow() + '<span class="m2flt">%s</span>' % pk([lab]) + arrow()) if lab else ""
        inner.append(step(node(ico(rt, 62), n, s) + tail))
    parts.append('<div class="m2zone" style="flex:1"><span class="m2zl">%s</span><div class="m2chain">%s</div>'
                 '<div class="m2cap" style="margin-top:6px">%s</div></div>' % (zone, "".join(inner), foot))
    parts.append(step(arrow() + node(ico(ip, 54), "IP-пакет", "(без метки)")))
    return '<div class="m2chain" style="align-items:center">%s</div>' % "".join(parts)


