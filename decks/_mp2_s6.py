def seq(rows, caps):
    """Диаграмма обмена (рисунки pptx 38–39) — как _mp_s2.seq, но рамки и подписи по размеру крупного кегля."""
    xs = {"LER1": 220, "LSR1": 560, "LSR2": 840, "LER2": 1120}
    nm = {"LER1": "LER1 — входной", "LSR1": "LSR1", "LSR2": "LSR2", "LER2": "LER2 — выходной"}
    b = []
    for k, x in xs.items():
        b.append(link(x, 70, x, 470, "#8a97ab", 3))
        b.append(box(x - 125, 16, 250, 50, nm[k], "#d8e8fb", BLUE, 16))
        b.append(box(x - 125, 466, 250, 50, nm[k], "#d8e8fb", BLUE, 16))
    y = 108
    for i, (kind, a, z, s) in enumerate(rows, 1):
        if kind == "m":
            x1, x2 = xs[a], xs[z]
            b.append(link(x1, y, x2 + (-6 if x2 > x1 else 6), y, ORG if x2 > x1 else RED, 4, ph=i, arrow=True))
            b.append(t((x1 + x2) / 2.0, y - 10, s, 15, INK, 800, extra=' data-ph="%d"' % i))
        else:
            x = xs[a]
            w = 24 + len(s) * 12.6
            b.append(box(min(max(x - w / 2.0, 5), 1335 - w), y - 18, w, 36, s, "#e3f7ea", GRN, 15, ph=i))
        y += 56
    return sc("".join(b), caps, "0 0 1340 520")

