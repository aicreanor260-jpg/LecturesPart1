def hdr(x, y, lab, ph=None, only=None):
    a = ""
    if only is not None:
        a = ' data-ph="%d" data-ph-only="1"' % only
    elif ph is not None:
        a = ' data-ph="%d"' % ph
    cells = [("Метка=\n%s" % lab, 84, "#ffe3c7"), ("SA", 40, "#fff"), ("DA=\n127.0.0.1", 104, "#fff"),
             ("FEC=\n105.0.0.0", 104, "#e3f7ea")]
    g, cx = ['<g%s>' % a], x
    for s, w, f in cells:
        g.append(box(cx, y, w, 50, s, f, INK, 15, rx=2))
        cx += w
    return "".join(g) + "</g>"


