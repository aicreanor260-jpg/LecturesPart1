def X(key):
    """Рисунок pptx, расшифрованный в _dk_tx: консоль, таблица, блок-схема."""
    d = TX.VLAN[key]
    k = d["kind"]
    if k == "cli":
        return term(d["lines"])
    if k == "table":
        return mtables(d["tables"], d.get("after", ""))
    if k == "flow":
        cols = [[dict(it, text=it["text"].replace("→ ", "").replace(" →", "").replace(" (общий)", ""))
                 for it in c] for c in d["columns"]]
        return flow(cols)
    raise ValueError(key)


