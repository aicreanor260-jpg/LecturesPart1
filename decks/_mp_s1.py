def stack_ops():
    b = []
    xs = [180, 480, 780, 1060]
    heads = [("Стек до", 0), ("Push 100", 1), ("Swap 200", 2), ("Pop", 3)]
    stacks = [[50], [100, 50], [200, 50], [50]]
    for (h, ph), x, st in zip(heads, xs, stacks):
        g = ['<g data-ph="%d">' % ph, t(x, 60, h, 22, BLUE if ph else INK, 900)]
        y = 300 - 46 * (len(st) + 1)
        for i, lb in enumerate(st):
            hot = (ph in (1, 2) and i == 0)
            g.append(box(x - 70, y + i * 46, 140, 42, str(lb), ORG if hot else "#ffe3c7", "#fff" if hot else INK, 20))
        g.append(box(x - 70, y + len(st) * 46, 140, 42, "IP", "#fff", BLUE, 20))
        g.append("</g>")
        b.append("".join(g))
        if ph:
            b.append(link(xs[ph - 1] + 85, 220, x - 85, 220, ORG, 4, ph=ph, arrow=True))
    b.append(t(600, 360, "Верхняя (последняя добавленная) метка обрабатывается первой — LIFO", 18, INK, 800))
    return "".join(b)
