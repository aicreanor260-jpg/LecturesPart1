def ltab(name, rows, note="", dots=True):
    d = [["…", "…", "…", "…"]] if dots else []
    return "<div>" + tbl(["Входной интерфейс", "Метка", "Следующий хоп", "Действие"], d + rows + d, name) + (
        '<div class="mt-n">%s</div>' % note if note else "") + "</div>"


