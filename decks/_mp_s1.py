def mpls_hdr(stack=False):
    """Формат MPLS-заголовка (pptx 15) / стек меток (pptx 16)."""
    b = []
    cells = ([("Заголовок канального уровня", 250, "#d7ecd9")] +
             ([("верхняя\nMPLS-метка", 150, "#d8e8fb"), ("нижняя\nMPLS-метка", 150, "#d8e8fb")] if stack
              else [("MPLS-заголовок", 170, "#d8e8fb")]) +
             [("Заголовок сетевого уровня", 250, "#d7ecd9"), ("Полезная нагрузка", 0, "#fff")])
    x = 20
    for s, w, f in cells:
        w = w or (1180 - x)
        b.append(box(x, 120, w, 70, s, f, INK, 16, rx=2))
        cells_x = x
        x += w
        if s.startswith("MPLS"):
            mx = (cells_x, x)
    if stack:
        b.append(link(270, 90, 570, 90, INK, 2, arrow=True))
        b.append(link(570, 90, 270, 90, INK, 2, arrow=True))
        b.append(t(420, 78, "Стек MPLS-меток", 17, INK, 800))
        b.append(link(270, 90, 270, 120, INK, 2, True))
        b.append(link(570, 90, 570, 120, INK, 2, True))
        return svg("".join(b), "0 0 1200 220")
    b.append(link(mx[0], 190, 60, 300, INK, 2, True))
    b.append(link(mx[1], 190, 860, 300, INK, 2, True))
    fl = [("Label (MPLS-метка)", 500, "#ffe3c7"), ("TC", 70, "#fff1b8"), ("S", 40, "#e6dcff"), ("TTL", 190, "#d8e8fb")]
    x = 60
    for (s, w, f), bits in zip(fl, ("0", "20", "23", "24")):
        b.append(box(x, 320, w, 70, s, f, INK, 18, rx=2))
        x += w
    for bx, s in ((60, "0"), (555, "19"), (625, "22"), (645, "23"), (850, "31")):
        b.append(t(bx, 310, s, 14, "#3a4b6e", 800))
