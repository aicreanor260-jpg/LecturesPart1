def lsp_chain(names, subs, labels, final="IP", title=""):
    """Цепочка LSP по шагам: пакет идёт слева направо, метка меняется на каждом узле."""
    n = len(names)
    xs = [140 + i * (920.0 / (n - 1)) for i in range(n)]
    b = [cloud(70, 70, 1060, 300, "#e6f3ff", "#86b9ee", title)]
    for i in range(n - 1):
        b.append(link(xs[i] + 34, 220, xs[i + 1] - 34, 220, "#5d7396", 5))
    for i, (nm, sb) in enumerate(zip(names, subs)):
        b.append(router(xs[i], 220, nm, ""))
        b.append(t(xs[i], 330, sb, 15, "#1a4f9c", 800, extra=' data-ph="%d"' % (i + 1)))
    b.append(pkt(20, 120, [], only=0))
    for i in range(n - 1):
        lab = labels[i]
        b.append(pkt((xs[i] + xs[i + 1]) / 2.0 - 40, 150, [lab] if lab else [], only=i + 1))
    b.append(pkt(xs[-1] + 40, 150, [], only=n))
    return "".join(b)


