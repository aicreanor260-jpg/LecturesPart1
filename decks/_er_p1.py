def tl(icon, html, tone="b", key=""):
    return step(I.tile(icon, html, tone, key))


def lay(label, title, cols, ratio="1fr 1fr", sub=""):
    """Слайд-сетка: cols — список колонок, в каждой готовые (уже обёрнутые в step) блоки."""
    body = "".join('<div class="col a-col">%s</div>' % "".join(c) for c in cols)
    slide(label, sc(head(title, sub), '<div class="g grow a-g" style="grid-template-columns:%s">%s</div>' % (ratio, body)))


def chain(items, cls=""):
    """Цепочка шагов слева направо: items — (номер/иконка, заголовок, html)."""
    out = []
    for i, (n, k, html) in enumerate(items):
        if i:
            out.append('<i class="a-arr">→</i>')
        out.append('<div class="a-st"><u>%s</u><b>%s</b><p>%s</p></div>' % (n, k, html))
    return step('<div class="a-chain %s">%s</div>' % (cls, "".join(out)))


def svg(body, vb):
    return step('<div class="a-fig">%s</div>' % fig(body, vb))


def photo(pins, cap=""):
    """Фото ESR-200 (паспорт Eltex) с выносками: pins — (x%, текст, цвет, сверху?)."""
    ps = "".join('<span class="a-pin %s" style="left:%g%%;--c:%s"><i></i>%s</span>' % ("up" if up else "dn", x, c, s)
                 for x, s, c, up in pins)
    c = '<figcaption>%s</figcaption>' % cap if cap else ""
    return step('<figure class="a-photo"><div class="a-ph"><img src="%s" alt="ESR-200">%s</div>%s</figure>'
                % (I._img("esr200.webp"), ps, c))


def frame(x, y, parts, h=40):
    """Кадр как ряд полей: parts — (ширина, подпись, цвет заливки)."""
    o, cx = [], x
    for w, s, c in parts:
        o.append('<rect x="%g" y="%g" width="%g" height="%g" rx="6" style="fill:%s;stroke:#fff" stroke-width="2"/>' % (cx, y, w, h, c))
        o.append(t(cx + w / 2.0, y + h / 2.0 + 6, s, 15, "#fff" if c[0] == "#" and c not in ("#fff", "#eef1ff") else INK, 800))
        cx += w
    return "".join(o)


