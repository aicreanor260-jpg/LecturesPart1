def clean(img, rects, tol=42):
    mask = np.zeros(img.shape[:2], np.uint8)
    for x0, y0, x1, y1 in rects:
        roi = img[y0:y1, x0:x1].reshape(-1, 3).astype(np.int32)
        q = (roi // 12) * 12  # фон прямоугольника — самый частый цвет
        keys, cnt = np.unique(q, axis=0, return_counts=True)
        bg = keys[cnt.argmax()] + 6
        d = np.abs(img[y0:y1, x0:x1].astype(np.int32) - bg).sum(axis=2)
        mask[y0:y1, x0:x1] = np.where(d > tol, 255, 0).astype(np.uint8)
    mask = cv2.dilate(mask, np.ones((5, 5), np.uint8), iterations=2)
    return cv2.inpaint(img, mask, 9, cv2.INPAINT_TELEA)


def main(src):
    os.makedirs(OUT, exist_ok=True)
    for name, (i, rects) in RECTS.items():
        img = cv2.imdecode(np.fromfile(os.path.join(src, "rip%d.jpg" % i), np.uint8), cv2.IMREAD_COLOR)
        out = clean(img, rects)
        out = clean(out, rects, 60)  # второй проход добирает ореолы букв
        cv2.imencode(".webp", out, [cv2.IMWRITE_WEBP_QUALITY, 84])[1].tofile(os.path.join(OUT, "p_%s.webp" % name))  # imwrite не понимает кириллицу в пути
        print(name)


if __name__ == "__main__":
    main(sys.argv[1])
