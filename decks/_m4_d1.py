def _bits29():
    """Побитовое сравнение 172.16.0.20 с маршрутами /12, /18, /26 (как на картинке pptx)."""
    rows = [("172.16.0.20/24", "IP-адрес назначения", 24), ("172.16.0.0/12", "Маршруты таблицы маршрутизации", 12),
            ("172.16.0.0/18", "", 18), ("172.16.0.0/26", "", 26)]
    oct_ = ["10101100", "00010000", "00000000"]
    o = []
    y = 40
    for i, (nm, cap, n) in enumerate(rows):
        last = "00010100" if i == 0 else "00000000"
        bits = "".join(oct_) + last
        if cap:
            o.append(S.t(20, y - 8, cap, 13, S.SOFT, 700, "start"))
        o.append(S.t(20, y + 22, nm, 15, S.GOLD2 if i != 3 else S.BLUE, 800, "start", mono=True))
        for k, ch in enumerate(bits):
            x = 220 + k * 30 + (k // 8) * 12
            on = k < n
            o.append('<rect x="%g" y="%g" width="27" height="30" rx="3" fill="%s" stroke="rgba(240,199,94,.4)"/>'
                     % (x, y, "rgba(155,227,122,.55)" if on else "rgba(255,255,255,.06)"))
            o.append(S.t(x + 13.5, y + 21, ch, 14, "#fff", 700, mono=True))
        y += 72 if i == 0 else 56
    o.append(S.t(600, y + 10, "Среди кандидатов самое длинное совпадение бит с IP-адресом назначения - это лучший маршрут", 14, S.GOLD2, 800))
    return fig(S.fig("".join(o), "0 0 1220 %d" % (y + 30)))


