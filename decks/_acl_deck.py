_PROMPT = re.compile(r"^(R1(?:\([^)]*\))?#)(.*)$")


def conf(lines, title="Конфигурация"):
    """Команды ESR: приглашение приглушено, команда выделена; [[…]] — подсветка как в pptx; прочие строки — как есть."""
    out = []
    for ln in lines:
        m = _PROMPT.match(ln)
        if m:
            s = '<span class="p">%s</span><span class="k">%s</span>' % (_esc(m.group(1)), _esc(m.group(2)))
        else:
            s = _esc(ln)
        s = s.replace("[[", '<span class="h">').replace("]]", "</span>")
        out.append(s)
    t = '<div class="clih">%s</div>' % _esc(title) if title else ""
    return '%s<pre class="cli">%s</pre>' % (t, "\n".join(out))


def term(lines, title=""):
    """Вывод консоли построчно, как на скриншоте pptx; [[…]] — подсветка."""
    t = '<div class="clih">%s</div>' % _esc(title) if title else ""
    body = "\n".join(_esc(l).replace("[[", '<span class="h">').replace("]]", "</span>") for l in lines)
    return '%s<pre class="cli term">%s</pre>' % (t, body)


def syn(lines, title="Синтаксис"):
    """Синтаксис команды: параметры курсивом (*…*)."""
    body = "\n".join(re.sub(r"\*([^*]+)\*", r"<i>\1</i>", _esc(l)) for l in lines)
    return '<div class="clih">%s</div><pre class="cli syn">%s</pre>' % (title, body)


def info(name, title):
    """Инфографика автора во весь слайд сразу за своим слайдом pptx."""
    with open(os.path.join(HERE, "_acl_assets", name + ".webp"), "rb") as fh:
        uri = "data:image/webp;base64," + base64.b64encode(fh.read()).decode()
    slide("Инфографика · " + re.sub("<[^>]+>", "", title),
          '<div class="aclbleed"><img src="%s" alt="" loading="lazy"></div>' % uri)


