def net(nodes, edges, root=None, badges=(), flows=(), T=5, extra="", w=120):
    """nodes {имя: (x,y)}; edges [(a, b, цвет, пунктир)]"""
    g = [ln("M%d,%d L%d,%d" % (nodes[a] + nodes[b]), c, 6, d) for a, b, c, d in edges]
    g += [psw(x, y, n, crown=(n == root), gold=(n == root), w=w) for n, (x, y) in nodes.items()]
    g += [badge(x, y, r) for x, y, r in badges]
    g += [env(p, t0, d, T) for p, t0, d in flows]
    return "".join(g) + extra


def L(*xy):
    return "M" + " L".join("%d,%d" % p for p in xy)


