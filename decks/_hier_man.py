def _agg_phys(storm=True):
    D1, D2 = (210, 60), (430, 60)
    accs = [(100, 250), (320, 250), (540, 250)]
    g = [ln(262, 52, 378, 52, OR, 3.4), ln(262, 68, 378, 68, OR, 3.4)]
    for k, (x, y) in enumerate(accs):
        g.append(ln(x - 12, y - 23, D1[0] - 30 + k * 30, D1[1] + 23))
        g.append(ln(x + 12, y - 23, D2[0] - 30 + k * 30, D2[1] + 23))
    g += [dev(*D1, name="DstSW1"), dev(*D2, name="DstSW2")] + [dev(x, y, "AccSW%d" % (k + 1)) for k, (x, y) in enumerate(accs)]
    if storm:
        loop = "M88,227 L180,83 L262,60 L378,60 L460,83 L112,227"
        g += [_env(loop, i * 0.7, 3.2, 4.2, "#ff8787") for i in range(5)]
        g.append('<text x="320" y="310" text-anchor="middle" font-weight="800" font-size="15">Множество петель → шторм</text>')
    return svg(640, 320, "".join(g))


def _stack():
    g = [frame(130, 10, 380, 100, "Стек DstSW"), dev(220, 70, "Unit1"), dev(420, 70, "Unit2"), ln(272, 62, 368, 62, OR, 3.4),
         ln(272, 78, 368, 78, OR, 3.4), oval(320, 70, 12, 22, OR)]
    for k, x in enumerate((100, 320, 540)):
        g += [ln(x - 12, 227, 200 + k * 20, 93), ln(x + 12, 227, 400 + k * 20, 93), oval(x, 215, 40, 12), dev(x, 250, "AccSW%d" % (k + 1))]
    g.append('<text x="320" y="310" text-anchor="middle" font-weight="800" font-size="15">Физически: стек + LAG на каждом коммутаторе доступа</text>')
    return svg(640, 320, "".join(g))


def _stack_log():
    g = [frame(240, 10, 160, 110, "Стек DstSW"), dev(320, 78, "Unit1", 110, 52, "Unit2")]
    for k, x in enumerate((100, 320, 540)):
        g += [ln(x, 227, 320, 104, "currentColor", 6), dev(x, 250, "AccSW%d" % (k + 1))]
    g.append('<text x="320" y="310" text-anchor="middle" font-weight="800" font-size="15">Логически: один коммутатор, петель нет</text>')
    return svg(640, 320, "".join(g))


