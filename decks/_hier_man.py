def pic(name):
    return K.pic(A, name)


def dev(x, y, name, w=104, h=46, sub=""):
    t = ('<text x="%d" y="%d" text-anchor="middle" fill="#fff" font-weight="800" font-size="15">%s</text>' % (x, y + (0 if sub else 5), name))
    if sub:
        t += '<text x="%d" y="%d" text-anchor="middle" fill="#fff" font-weight="800" font-size="15">%s</text>' % (x, y + 17, sub)
    return '<rect x="%d" y="%d" width="%d" height="%d" rx="9" fill="%s"/>%s' % (x - w // 2, y - h // 2, w, h, SWC, t)


def ln(x1, y1, x2, y2, c="currentColor", w=2.6, dash=""):
    return '<path d="M%d,%d L%d,%d" stroke="%s" stroke-width="%s" fill="none" %s/>' % (x1, y1, x2, y2, c, w, 'stroke-dasharray="%s"' % dash if dash else "")


def oval(x, y, rx=26, ry=11, c="currentColor"):
    return '<ellipse cx="%d" cy="%d" rx="%d" ry="%d" fill="none" stroke="%s" stroke-width="2.4"/>' % (x, y, rx, ry, c)


def frame(x, y, w, h, label):
    return ('<rect x="%d" y="%d" width="%d" height="%d" fill="none" stroke="currentColor" stroke-width="2" stroke-dasharray="7 5"/>'
            '<text x="%d" y="%d" text-anchor="middle" font-weight="800" font-size="15">%s</text>' % (x, y, w, h, x + w // 2, y + 20, label))


