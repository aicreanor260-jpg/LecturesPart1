def pico(name):
    return ('<svg class="ixp" viewBox="0 0 48 48" fill="none" stroke="currentColor" stroke-width="3.2" '
            'stroke-linecap="round" stroke-linejoin="round">%s</svg>' % PIC[name])


def tl(icon, html, tone="b", key=""):
    k = '<b class="ixk">%s</b>' % key if key else ""
    return '<div class="ixt t-%s">%s<div>%s<p>%s</p></div></div>' % (tone, pico(icon), k, html)


def defb(html, tag=""):
    tg = '<span class="ixtag">%s</span>' % tag if tag else ""
    return '<div class="ixdef">%s<p>%s</p></div>' % (tg, html)


def cols(*cs, cls="c-g2"):
    return '<div class="g grow %s">%s</div>' % (cls, "".join('<div class="col">%s</div>' % c for c in cs))


def page(label, title, body, sub=""):
    slide(label, sc(head(title, sub), body))


def steps(*blocks):
    return "".join(step(b) for b in blocks)


def flow(items, tone="b"):
    """Горизонтальный/вертикальный поток шагов: [(номер, иконка, html)]."""
    o = []
    for i, (n, ic, html) in enumerate(items):
        o.append(step('<div class="c-fs t-%s"><u>%s</u>%s<p>%s</p></div>' % (tone, n, pico(ic), html)))
    return '<div class="c-flow">%s</div>' % "".join(o)


def chips(items):
    return '<div class="c-chips">%s</div>' % "".join('<span class="t-%s">%s%s</span>' % (tn, pico(ic), s) for ic, s, tn in items)


