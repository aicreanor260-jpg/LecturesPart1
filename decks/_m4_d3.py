# -*- coding: utf-8 -*-
"""Дека 2.4, pptx 62–75: примеры работы таблицы R1, изменение таблицы при up/down, TTL, путь пакета через R1–R3."""
from _sw_lib import card, p
from _m4_kit import src, tx, items, pslide, long_slides, info, fig, scn, T
import _m4_fig3 as H
from _m4_fig3 import P_PC1, P_SW1, P_R1, P_SW3, P_PC3, P_R2, P_SW5, P_PC5
import _m4_d1


def ol(xs, start=1):
    return '<ol class="li" start="%d">%s</ol>' % (start, "".join("<li>%s</li>" % x for x in xs))


def build():
    TE = "Пример <em>таблицы маршрутизации</em>"
    # ---------------------------------------------------------------- pptx 62
    pslide("Пример таблицы R1", TE, [card("", p(src(62)[1]), "cy")],
           [scn(H.topo_ex(route=[(150, 40), (300, 60), (150, 150)]), ["ПК1 192.168.10.254 → ПК2 192.168.10.35",
                                                                        "ПК1 → коммутатор", "коммутатор → ПК2 (R1 не участвует)"])])
    pslide("Таблица R1", TE, [T(62, 1)])
    # ---------------------------------------------------------------- pptx 63–66
    ex = {63: ([P_PC1, P_SW1, P_R1], ["Пример 1: ПК1 → 192.168.10.1", "ПК1 → коммутатор", "→ Gi1/0/1 R1: адрес R1"]),
          64: ([P_PC1, P_SW1, P_R1, P_SW3, P_PC3], ["Пример 2: ПК1 → ПК3", "ПК1 → коммутатор", "→ R1 Gi1/0/1",
                                                     "R1: C 192.168.20.0/24 → Gi1/0/2", "→ ПК3"]),
          65: ([P_PC1, P_SW1, P_R1, P_R2], ["Пример 3: ПК1 → 203.0.113.2", "ПК1 → коммутатор", "→ R1 Gi1/0/1",
                                             "R1: C 203.0.113.0/24 → Gi1/0/3 → R2"]),
          66: ([P_PC1, P_SW1, P_R1, P_R2, P_SW5, P_PC5], ["Пример 4: ПК1 → 10.10.20.254", "ПК1 → коммутатор", "→ R1 Gi1/0/1",
                                                           "R1: O 10.10.20.0/24 via 203.0.113.2 → Gi1/0/3", "R2 → коммутатор", "→ узел 10.10.20.254"])}
    for n in (63, 64, 65, 66):
        route, caps = ex[n]
        t = src(n)[1]
        h, it = items(t)
        term_i = 0 if n in (63, 64) else 1
        if it:
            pslide("Пример %d" % (n - 62), TE, [card("", p(h) + ol(it[:2]), "cy")], [scn(H.topo_ex(route=route), caps)])
            if it[2:]:
                pslide("Пример %d · 2" % (n - 62), TE, [card("", ol(it[2:], 3), "mg")], [fig(H.topo_ex(route=route))])
        else:
            long_slides("Пример %d" % (n - 62), TE, [t], per=340,
                        rights=[[scn(H.topo_ex(route=route), caps)], [fig(H.topo_ex(route=route))], [fig(H.topo_ex(route=route))]])
        pslide("Пример %d: таблица R1" % (n - 62), TE, [T(n, term_i)])
    # ---------------------------------------------------------------- pptx 67
    t67 = src(67)
    pslide("Интерфейс up/down", TE, [card("", p(t67[0]), "cy"), card("", p(t67[2]), "mg")], [T(67, 0)])
    # ---------------------------------------------------------------- pptx 68
    t68 = src(68)
    pslide("Пример 1: все интерфейсы up", TE, [card("", p(t68[0]), "cy")], [T(68, 1)])
    pslide("Пример 2: отключение интерфейсов", TE, [card("", p(t68[2]), "rd")], [T(68, 0)])
    # ---------------------------------------------------------------- pptx 69
    TP = "Путь <em>пакета по сети</em>"
    long_slides("Время жизни TTL", TP, [src(69)[1]], per=900)
    info("Путь пакета · инфографика", TP, "i_path")
    # ---------------------------------------------------------------- pptx 70
    t70 = src(70)
    long_slides("Маршрутизация пакета", "Маршрутизация <em>пакета</em>", [t70[2]], per=850,
                rights=[[_m4_d1._frame14()], [_m4_d1._frame14()]])
    # ---------------------------------------------------------------- pptx 71
    pslide("Адреса L2 и L3 на пути", "Маршрутизация <em>пакета</em>", [card("", p(src(71)[0]), "cy")], [fig(H.osi_path())])
    # ---------------------------------------------------------------- pptx 72
    TS = "Отправка <em>пакета</em>"
    long_slides("Отправка пакета", TS, [src(72)[1]], per=700,
                rights=[[fig(H.path_topo("ПК1", "1")), fig(H.frame_l2l3(("AA:11", "AA:AA")))]] * 4)
    # ---------------------------------------------------------------- pptx 73
    t73 = src(73)[2]
    k = t73.index("Пакет IP инкапсулируется")
    long_slides("Пересылка на следующий переход", TS + " · пересылка на следующий переход", [t73[:k]], per=700,
                rights=[[fig(H.path_topo("R1", "1")), fig(H.frame_l2l3(("AA:11", "AA:AA")))]] * 3)
    long_slides("R1 → R2: новый кадр", TS + " · пересылка на следующий переход", [t73[k:]], per=700,
                rights=[[fig(H.path_topo("R1", "234")), fig(H.frame_l2l3(("CC:33", "BB:22")))]] * 3)
    # ---------------------------------------------------------------- pptx 74
    t74 = src(74)
    TD = "Дальнейшее <em>движение пакета</em>"
    long_slides("Дальнейшее движение пакета", TD, [t74[1]], per=700,
                rights=[[fig(H.path_topo("R2", "234")), fig(H.frame_l2l3(("CC:33", "BB:22")))]] * 3)
    pslide("PPP: IP over E1", TD, [card("", p(t74[2]), "am")],
           [fig(H.path_topo("R2", "34")), fig(H.frame_l2l3(("FF:FF", "0x00")))])
    # ---------------------------------------------------------------- pptx 75
    t75 = src(75)
    TA = "Достижение <em>места назначения</em>"
    pslide("Достижение места назначения", TA, [card("", p(t75[1]), "cy")],
           [fig(H.path_topo("R3", "34")), fig(H.frame_l2l3(("FF:FF", "0x00")))])
    long_slides("R3 → ПК2", TA, [t75[2]], per=700,
                rights=[[fig(H.path_topo("ПК2", "4")), fig(H.frame_l2l3(("BB:BB", "DD:44")))]] * 3)
