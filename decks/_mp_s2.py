def seq(rows, caps):
    """Диаграмма обмена (pptx 38–39): линии жизни LER1, LSR1, LSR2, LER2; сообщения и действия по шагам."""
    xs = {"LER1": 130, "LSR1": 450, "LSR2": 700, "LER2": 1000}
    nm = {"LER1": "LER1 — входной", "LSR1": "LSR1", "LSR2": "LSR2", "LER2": "LER2 — выходной"}
    b = []
    for k, x in xs.items():
        b.append(link(x, 70, x, 470, "#8a97ab", 3))
        b.append(box(x - 95, 20, 190, 44, nm[k], "#d8e8fb", BLUE, 16))
        b.append(box(x - 95, 470, 190, 44, nm[k], "#d8e8fb", BLUE, 16))
    y = 100
    for i, (kind, a, z, s) in enumerate(rows, 1):
        if kind == "m":
            x1, x2 = xs[a], xs[z]
            b.append(link(x1, y, x2 + (-6 if x2 > x1 else 6), y, ORG if x2 > x1 else RED, 4, ph=i, arrow=True))
            b.append(t((x1 + x2) / 2.0, y - 10, s, 16, INK, 800, extra=' data-ph="%d"' % i))
        else:
            x = xs[a]
            w = 16 + len(s) * 9.2
            b.append(box(min(max(x - w / 2.0, 5), 1195 - w), y - 18, w, 34, s, "#e3f7ea", GRN, 15, ph=i))
        y += 52
    return sc("".join(b), caps, "0 0 1200 520")


