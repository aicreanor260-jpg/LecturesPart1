def mid(a, b, dy=-14):
    (x1, y1), (x2, y2) = N[a], N[b]
    return (x1 + x2) / 2.0, (y1 + y2) / 2.0 + dy


def ldp_net(body_extra="", lsp1=True):
    b = []
    for nm, x, y, r in NETS:
        b.append(link(N[r][0], N[r][1], x, y, "#5d7396", 3))
    for a, z in E:
        b.append(link(N[a][0], N[a][1], N[z][0], N[z][1], "#5d7396", 5))
    b.append(link(20, 330, 118, 330, "#5d7396", 4))
    b.append(link(830, 400, 900, 440, "#5d7396", 4))
    if lsp1:
        b.append(path("M170 345 Q300 360 365 345 L310 425", GRN, 4, True))
        b.append(t(345, 395, "LSP1", 18, GRN, 900))
    for nm, x, y, r in NETS:
        b.append(netcloud(x, y, nm))
    for nm, (x, y) in N.items():
        b.append(router(x, y, nm))
    return "".join(b) + body_extra


