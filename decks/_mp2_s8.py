def hop(pill, cls="gr"):
    """Стрелка перехода с пилюлей над ней (как «✓ ≥ 10 Мбит/с» в инфографике)."""
    return '<div class="m8hop"><span class="m2pill %s">%s</span><span class="m2ar">→</span></div>' % (cls, pill)


def var_net(v):
    """Вариант распределения потоков (живая вёрстка схемы из i60a): A–B–C сверху, A–D–E–C снизу."""
    A, B, C, D, E = (70, 150), (300, 110), (540, 150), (190, 250), (420, 250)
    top_c, bot_c = (ORG, BLUE) if v == 1 else (GRN, ORG)
    top_l, bot_l = (("Потоки 1 + 2:\n90 Мбит/с", "Поток 3:\n30 Мбит/с") if v == 1
                    else ("Потоки 2 + 3:\n70 Мбит/с", "Поток 1:\n50 Мбит/с"))
    fill = {ORG: "#ffe3c7", BLUE: "#d6ebfb", GRN: "#e3f7ea"}
    b = []
    for p1, p2, col in ((A, B, top_c), (B, C, top_c), (A, D, bot_c), (D, E, bot_c), (E, C, bot_c)):
        b.append(link(p1[0], p1[1], p2[0], p2[1], col, 6))
    b += [t(185, 160, "155 Мбит/с", 11, INK, 800), t(420, 160, "155 Мбит/с", 11, INK, 800),
          t(80, 230, "100 Мбит/с", 11, INK, 800), t(305, 290, "100 Мбит/с", 11, INK, 800), t(535, 230, "100 Мбит/с", 11, INK, 800)]
    b.append(box(120, 20, 150, 52, top_l, fill[top_c], INK, 11, stroke=top_c))
    b.append(box(230, 175, 150, 52, bot_l, fill[bot_c], INK, 11, stroke=bot_c))
    for nm, (x, y) in (("A", A), ("B", B), ("C", C), ("D", D), ("E", E)):
        b.append(router(x, y, nm, r=26))
    return svg("".join(b), "0 0 610 310")


